-- OB 资源诊断：服务器剩余 CPU/内存 + 已分配 unit 一览
SELECT SVR_IP, CPU_CAPACITY, CPU_ASSIGNED,
       ROUND(MEM_CAPACITY/1024/1024/1024,1) AS MEM_CAP_GB,
       ROUND(MEM_ASSIGNED/1024/1024/1024,1) AS MEM_ASG_GB,
       ROUND(LOG_DISK_CAPACITY/1024/1024/1024,1) AS LOG_CAP_GB,
       ROUND(LOG_DISK_ASSIGNED/1024/1024/1024,1) AS LOG_ASG_GB
  FROM GV$OB_SERVERS;

SELECT NAME, MAX_CPU, MIN_CPU, ROUND(MEMORY_SIZE/1024/1024/1024,1) AS MEM_GB,
       ROUND(LOG_DISK_SIZE/1024/1024/1024,1) AS LOG_GB
  FROM DBA_OB_UNIT_CONFIGS;

SELECT UNIT_ID, TENANT_ID, MAX_CPU, MIN_CPU,
       ROUND(MEMORY_SIZE/1024/1024/1024,1) AS MEM_GB,
       ROUND(LOG_DISK_SIZE/1024/1024/1024,1) AS LOG_GB
  FROM DBA_OB_UNITS;
