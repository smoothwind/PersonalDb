//! 分页模板真实执行 + 会话管理端到端集成测试。
//!
//! 分页：复刻前端 `utils/sqlTemplates.ts#builtinPaged` 的两条模板（ROWNUM 包装
//! pdb_rn / `pdb_p LIMIT OFFSET`），在真实引擎上执行第二页（offset 5 limit 5），
//! 断言行窗口与列形状（Oracle 原始驱动应含 pdb_rn 列——应用物化层丢弃属既定 P2）。
//!
//! 会话：执行方言 `server_sessions_sql`（固定列契约）→ 建第二连接 → 取其会话 id →
//! 方言 `kill_session_sql` 终止 → B 下一条查询报错（连接被杀端到端）。
//! Oracle 对普通用户通常无 v$session 权限 → 优雅跳过（非产品缺陷）。
//!
//! env 门控（PDB_IT_MYSQL / PDB_IT_OBM / PDB_IT_PG / PDB_IT_GAUSS / PDB_IT_ORACLE）。

