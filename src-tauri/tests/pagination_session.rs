async fn exec(driver: &Arc<dyn DatabaseDriver>, sql: &str) -> personal_db_lib::db::types::QueryResult {
    driver.execute(None, sql, 10_000).await.unwrap()
}

fn as_f64(v: &CellValue) -> f64 {
    match v {
        CellValue::Int(i) => *i as f64,
        CellValue::UInt(u) => *u as f64,
        CellValue::Float(f) => *f,
        CellValue::Text(s) => s.trim().parse::<f64>().unwrap_or(f64::NAN),
        other => panic!("期望数值，实际 {other:?}"),
    }
}

fn text_of(v: &CellValue) -> String {
    match v {
        CellValue::Text(s) => s.clone(),
        CellValue::Int(i) => i.to_string(),
        CellValue::UInt(u) => u.to_string(),
        CellValue::Float(f) => format!("{f}"),
        other => format!("{other:?}"),
    }
}

// =============================================================================
// 分页模板真实执行（第二页 offset 5 limit 5 → id 6..10）
// =============================================================================

/// 复刻 utils/sqlTemplates.ts#builtinPaged 的两条模板
fn paged_wrap(flavor: Flavor, inner: &str, offset: u32, limit: u32) -> String {
    match flavor {
        Flavor::Oracle => format!(
            "SELECT * FROM (SELECT t.*, ROWNUM pdb_rn FROM ({inner}) t WHERE ROWNUM <= {end}) WHERE pdb_rn > {offset}",
            end = offset + limit
        ),
        _ => format!("SELECT * FROM ({inner}) pdb_p LIMIT {limit} OFFSET {offset}"),
    }
}

async fn paging_battery(kind: DbKind, flavor: Flavor) {
    let driver = create_driver(&cfg_for(kind)).expect("create_driver");
    let _ = driver.execute(None, "DROP TABLE IF EXISTS it_pgnd", 0).await;
    let _ = driver.execute(None, "DROP TABLE \"it_pgnd\"", 0).await;

    let create = match flavor {
        Flavor::MySql => "CREATE TABLE it_pgnd (id INT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(20))",
        Flavor::Pg => "CREATE TABLE it_pgnd (id SERIAL PRIMARY KEY, code TEXT)",
        Flavor::Oracle => "CREATE TABLE it_pgnd (id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, code VARCHAR2(20))",
    };
    exec(&driver, create).await;
    for i in 1..=12 {
        exec(&driver, &format!("INSERT INTO it_pgnd (code) VALUES ('C{i:02}')")).await;
    }

    // 第二页：offset 5 limit 5（内层 ORDER BY 保证窗口稳定）
    let inner = "SELECT id, code FROM it_pgnd ORDER BY id";
    let sql = paged_wrap(flavor, inner, 5, 5);
    let r = exec(&driver, &sql).await;

    assert_eq!(r.rows.len(), 5, "第二页应恰 5 行: {:?}", r.rows.len());
    let ids: Vec<f64> = r.rows.iter().map(|row| as_f64(&row[0])).collect();
    for (idx, id) in ids.iter().enumerate() {
        assert!(num_eq(*id, (6 + idx) as f64), "第 {} 行 id 应为 {}，实际 {}", idx + 1, 6 + idx, id);
    }
    // 列形状：MySQL/PG 系别名 pdb_p 不泄漏；Oracle 原始驱动含 pdb_rn 列（应用物化层丢弃，P2 既定）
    match flavor {
        Flavor::Oracle => {
            assert!(
                r.columns.iter().any(|c| c.name.to_uppercase() == "PDB_RN"),
                "Oracle 原始结果应含 ROWNUM 别名列: {:?}",
                r.columns.iter().map(|c| &c.name).collect::<Vec<_>>()
            );
            eprintln!("paging ✓（含 pdb_rn 原始列——应用物化层丢弃为既定 P2）");
        }
        _ => {
            assert!(
                !r.columns.iter().any(|c| c.name.to_lowercase().contains("pdb_p")),
                "别名 pdb_p 不应泄漏: {:?}",
                r.columns.iter().map(|c| &c.name).collect::<Vec<_>>()
            );
            eprintln!("paging ✓（列形状干净）");
        }
    }

    // 边界页：首页（offset 0）与超界页（offset 20）
    let first = exec(&driver, &paged_wrap(flavor, inner, 0, 5)).await;
    assert_eq!(first.rows.len(), 5);
    assert!(num_eq(as_f64(&first.rows[0][0]), 1.0), "首页首行 id=1");
    let beyond = exec(&driver, &paged_wrap(flavor, inner, 20, 5)).await;
    assert_eq!(beyond.rows.len(), 0, "超界页应空");
    let _ = driver.execute(None, "DROP TABLE it_pgnd", 0).await;
    let _ = driver.execute(None, "DROP TABLE \"it_pgnd\"", 0).await;
    eprintln!("[{kind:?}] 分页模板 ✓");
}

fn num_eq(a: f64, b: f64) -> bool {
    (a - b).abs() < 1e-9
}

