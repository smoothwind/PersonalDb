// =============================================================================
// 会话管理端到端
// =============================================================================

async fn sessions_battery(kind: DbKind, flavor: Flavor) {
    let driver = create_driver(&cfg_for(kind)).expect("create_driver");
    let dia = driver.dialect();
    let sql = match dia.server_sessions_sql() {
        Some(s) => s,
        None => panic!("{kind:?} 声明支持会话却无 SQL"),
    };

    // 第二连接（独立 processlist/backend 条目）
    let b = create_driver(&cfg_for(kind)).unwrap();
    // 各方言的会话 id 查询与探活语句
    let (id_sql, probe_sql) = match flavor {
        Flavor::MySql => ("SELECT CONNECTION_ID()", "SELECT 1"),
        Flavor::Pg => ("SELECT pg_backend_pid()", "SELECT 1"),
        Flavor::Oracle => (
            "SELECT SID || ',' || SERIAL# FROM V$SESSION WHERE AUDSID = USERENV('SESSIONID')",
            "SELECT 1 FROM DUAL",
        ),
    };
    // 取 B 的会话 id（Oracle 需 V$SESSION 读权限，普通用户可能 ORA-00942 → 优雅跳过）
    let id_val = match b.execute(None, id_sql, 1).await {
        Ok(r) => text_of(&r.rows[0][0]),
        Err(e) => {
            if flavor == Flavor::Oracle {
                eprintln!("sessions 跳过（Oracle 无 V$SESSION 读权限，环境限制）: {e}");
                return;
            }
            panic!("取 B 会话 id 失败: {e}");
        }
    };

    // 会话列表执行 + 固定列契约（首列 id）
    let r = exec(&driver, &sql).await;
    assert!(!r.rows.is_empty(), "会话列表应非空");
    assert_eq!(r.columns[0].name.to_lowercase(), "id", "首列应为 id: {:?}", r.columns.iter().map(|c| &c.name).collect::<Vec<_>>());
    eprintln!("sessions 列表 ✓（{} 行）", r.rows.len());

    // kill B：服务端终止旧会话；受害方连接池会透明重建（新会话 id）——
    // 契约断言 = 旧会话 id 必须消失（旧连接探活报错或 id 变化都算终止生效）
    let kill = dia.kill_session_sql(&id_val, "kill");
    match kill {
        Some(k) => {
            if let Err(e) = driver.execute(None, &k, 0).await {
                let msg = format!("{e}");
                let up = msg.to_uppercase();
                if up.contains("PRIV") || up.contains("1044") || up.contains("01031") {
                    eprintln!("kill 跳过（权限不足，环境限制）: {msg}");
                    return;
                }
                panic!("kill 失败: {msg}");
            }
            let _ = b.execute(None, probe_sql, 1).await; // 触发池对死亡连接的处理
            let new_id = match b.execute(None, id_sql, 1).await {
                Ok(r) => Some(text_of(&r.rows[0][0])),
                Err(_) => None, // 旧连接探活/取 id 直接报错——终止已生效
            };
            match new_id {
                Some(ref nid) => assert!(*nid != id_val, "KILL 后 B 会话 id 应变化: {id_val} -> {nid}"),
                None => eprintln!("kill 端到端 ✓（旧连接查询报错——终止生效）"),
            }
            if let Some(ref nid) = new_id {
                eprintln!("kill 端到端 ✓（旧会话 {id_val} 已终止，池透明重建为 {nid}）");
            }
        }
        None => panic!("{kind:?} 声明支持会话却无 kill SQL"),
    }
}

